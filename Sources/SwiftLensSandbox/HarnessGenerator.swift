import SwiftLensCore
import SwiftSyntax

/// The two Swift files compiled into a preview dylib.
public struct GeneratedHarness: Sendable {
    /// The user's snippet with `#Preview` blocks blanked out (line numbers preserved) and `@main` removed.
    public var snippetSource: String
    /// Generated wrappers, the preview table and the C entry points used by the renderer.
    public var harnessSource: String
    public var entries: [PreviewEntry]
}

/// Generates the render harness for a snippet.
///
/// The preview bodies are moved into generated `View` structs so they compile *without* the PreviewsMacros
/// plugin (no Xcode project, no DeveloperToolsSupport registry). `@Previewable` declarations become real
/// properties of the wrapper, and `#sourceLocation` keeps compiler errors pointing at the user's lines.
public enum HarnessGenerator {
    /// C symbols exported by every harness. The renderer resolves them with `dlsym`.
    public enum Symbol {
        public static let previewCount = "swiftlens_preview_count"
        public static let previewName = "swiftlens_preview_name"
        public static let renderPNG = "swiftlens_render_png"
        public static let makeNSView = "swiftlens_make_nsview"
        public static let abiVersion = "swiftlens_abi_version"
    }

    public static let abiVersion: Int32 = 1

    public static func generate(_ document: SourceDocument, snippetPath: String? = nil) -> GeneratedHarness {
        let entries = PreviewExtractor.extract(document)
        let snippet = blankOut(document)
        var harness = """
        // Generated by SwiftLens. Do not edit: regenerated on every render.
        import SwiftUI
        import Foundation
        #if canImport(AppKit)
        import AppKit
        #endif


        """

        let sourceFile = (snippetPath ?? document.fileName).replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"")
        for entry in entries {
            harness += "struct \(wrapperName(entry.id)): View {\n"
            for declaration in entry.previewableDeclarations {
                harness += "    \(declaration)\n"
            }
            harness += "    var body: some View {\n"
            harness += "#sourceLocation(file: \"\(sourceFile)\", line: \(entry.bodyLine))\n"
            harness += entry.body.isEmpty ? "        EmptyView()\n" : entry.body + "\n"
            harness += "#sourceLocation()\n"
            harness += "    }\n}\n\n"
        }

        let names = entries.map { "\"" + escape($0.name) + "\"" }.joined(separator: ", ")
        harness += "let __swiftLensPreviewNames: [String] = [\(names)]\n\n"
        harness += "@MainActor func __swiftLensMakeView(_ index: Int) -> AnyView {\n    switch index {\n"
        for entry in entries {
            harness += "    case \(entry.id): return AnyView(\(wrapperName(entry.id))())\n"
        }
        harness += "    default: return AnyView(Text(\"SwiftLens: no preview #\\(index)\"))\n    }\n}\n\n"
        harness += HarnessRuntime.source
        return GeneratedHarness(snippetSource: snippet, harnessSource: harness, entries: entries)
    }

    static func wrapperName(_ index: Int) -> String { "__SwiftLensPreview_\(index)" }

    static func escape(_ text: String) -> String {
        text.replacingOccurrences(of: "\\", with: "\\\\").replacingOccurrences(of: "\"", with: "\\\"").replacingOccurrences(of: "\n", with: "\\n")
    }

    /// Removes `#Preview` blocks and `@main` without shifting line numbers.
    static func blankOut(_ document: SourceDocument) -> String {
        var ranges: [Range<Int>] = PreviewExtractor.previewMacroNodes(in: document).map {
            $0.positionAfterSkippingLeadingTrivia.utf8Offset..<$0.endPositionBeforeTrailingTrivia.utf8Offset
        }
        final class MainFinder: SyntaxVisitor {
            var ranges: [Range<Int>] = []
            override func visit(_ node: AttributeSyntax) -> SyntaxVisitorContinueKind {
                if node.attributeName.trimmedDescription == "main" {
                    ranges.append(node.positionAfterSkippingLeadingTrivia.utf8Offset..<node.endPositionBeforeTrailingTrivia.utf8Offset)
                }
                return .skipChildren
            }
        }
        let finder = MainFinder(viewMode: .sourceAccurate)
        finder.walk(document.tree)
        ranges += finder.ranges
        ranges.sort { $0.lowerBound < $1.lowerBound }

        let bytes = Array(document.text.utf8)
        var output: [UInt8] = []
        output.reserveCapacity(bytes.count)
        var cursor = 0
        for range in ranges where range.lowerBound >= cursor {
            output += bytes[cursor..<range.lowerBound]
            // Keep newlines so that every following line keeps its number.
            for byte in bytes[range] { output.append(byte == UInt8(ascii: "\n") ? byte : UInt8(ascii: " ")) }
            cursor = range.upperBound
        }
        output += bytes[cursor...]
        return String(decoding: output, as: UTF8.self)
    }
}

/// Swift source for the harness runtime: config decoding, environment application, rendering and C entry points.
enum HarnessRuntime {
    static let source = #"""
    // MARK: - SwiftLens runtime

    @_cdecl("swiftlens_abi_version")
    public func swiftlens_abi_version() -> Int32 { 1 }

    @_cdecl("swiftlens_preview_count")
    public func swiftlens_preview_count() -> Int32 { Int32(__swiftLensPreviewNames.count) }

    @_cdecl("swiftlens_preview_name")
    public func swiftlens_preview_name(_ index: Int32) -> UnsafeMutablePointer<CChar>? {
        guard index >= 0, Int(index) < __swiftLensPreviewNames.count else { return nil }
        return strdup(__swiftLensPreviewNames[Int(index)])
    }

    #if canImport(AppKit)
    struct __SwiftLensConfig: Decodable {
        var label: String = "default"
        var layout: String = "sizeThatFits"
        var width: Double?
        var height: Double?
        var colorScheme: String = "light"
        var dynamicTypeSize: String = "large"
        var locale: String?
        var layoutDirection: String = "leftToRight"
        var scale: Double = 2
        var engine: String = "appKit"
        var opaqueBackground: Bool = true
    }

    struct __SwiftLensRenderResult: Encodable {
        var pixelWidth: Int = 0
        var pixelHeight: Int = 0
        var pointWidth: Double = 0
        var pointHeight: Double = 0
        var error: String?
    }

    func __swiftLensDynamicTypeSize(_ name: String) -> DynamicTypeSize {
        switch name {
        case "xSmall": return .xSmall
        case "small": return .small
        case "medium": return .medium
        case "xLarge": return .xLarge
        case "xxLarge": return .xxLarge
        case "xxxLarge": return .xxxLarge
        case "accessibility1": return .accessibility1
        case "accessibility2": return .accessibility2
        case "accessibility3": return .accessibility3
        case "accessibility4": return .accessibility4
        case "accessibility5": return .accessibility5
        default: return .large
        }
    }

    func __swiftLensDecodeConfig(_ json: UnsafePointer<CChar>) -> __SwiftLensConfig {
        let data = Data(String(cString: json).utf8)
        return (try? JSONDecoder().decode(__SwiftLensConfig.self, from: data)) ?? __SwiftLensConfig()
    }

    func __swiftLensEncode(_ result: __SwiftLensRenderResult) -> UnsafeMutablePointer<CChar>? {
        let data = (try? JSONEncoder().encode(result)) ?? Data("{}".utf8)
        return strdup(String(decoding: data, as: UTF8.self))
    }

    @MainActor func __swiftLensConfigured(_ index: Int, _ config: __SwiftLensConfig, forLiveView: Bool) -> AnyView {
        var view = AnyView(
            __swiftLensMakeView(index)
                .environment(\.colorScheme, config.colorScheme == "dark" ? .dark : .light)
                .environment(\.dynamicTypeSize, __swiftLensDynamicTypeSize(config.dynamicTypeSize))
                .environment(\.layoutDirection, config.layoutDirection == "rightToLeft" ? .rightToLeft : .leftToRight)
        )
        if let locale = config.locale {
            view = AnyView(view.environment(\.locale, Locale(identifier: locale)))
        }
        if !forLiveView, config.layout == "fixed", let width = config.width, let height = config.height {
            view = AnyView(view.frame(width: width, height: height))
        }
        if config.opaqueBackground {
            view = AnyView(view.background(Color(nsColor: .windowBackgroundColor)))
        }
        return view
    }

    @MainActor func __swiftLensWritePNG(_ rep: NSBitmapImageRep, to path: String) -> String? {
        guard let png = rep.representation(using: .png, properties: [:]) else { return "PNG encoding failed" }
        do {
            try png.write(to: URL(fileURLWithPath: path))
            return nil
        } catch {
            return "Could not write \(path): \(error)"
        }
    }

    @MainActor func __swiftLensRender(_ index: Int, _ config: __SwiftLensConfig, _ path: String) -> __SwiftLensRenderResult {
        _ = NSApplication.shared
        let root = __swiftLensConfigured(index, config, forLiveView: false)
        let appearance = NSAppearance(named: config.colorScheme == "dark" ? .darkAqua : .aqua)
        var result = __SwiftLensRenderResult()

        if config.engine == "imageRenderer" {
            let renderer = ImageRenderer(content: root)
            renderer.scale = config.scale
            if config.layout == "fixed", let width = config.width, let height = config.height {
                renderer.proposedSize = ProposedViewSize(width: width, height: height)
            }
            guard let image = renderer.cgImage else {
                result.error = "ImageRenderer produced no image (the view may contain platform controls; try the AppKit engine)"
                return result
            }
            let rep = NSBitmapImageRep(cgImage: image)
            result.pixelWidth = image.width
            result.pixelHeight = image.height
            result.pointWidth = Double(image.width) / config.scale
            result.pointHeight = Double(image.height) / config.scale
            result.error = __swiftLensWritePNG(rep, to: path)
            return result
        }

        let hosting = NSHostingView(rootView: root)
        hosting.appearance = appearance
        var size: CGSize
        if config.layout == "fixed", let width = config.width, let height = config.height {
            size = CGSize(width: width, height: height)
        } else {
            size = hosting.fittingSize
        }
        size.width = min(max(size.width.rounded(.up), 1), 4096)
        size.height = min(max(size.height.rounded(.up), 1), 4096)

        let window = NSWindow(contentRect: NSRect(origin: .zero, size: size), styleMask: [.borderless], backing: .buffered, defer: false)
        window.isReleasedWhenClosed = false
        window.appearance = appearance
        window.contentView = hosting
        hosting.frame = NSRect(origin: .zero, size: size)
        hosting.layoutSubtreeIfNeeded()
        // Give SwiftUI a couple of run-loop turns to commit its first transaction (onAppear, task, async images).
        RunLoop.current.run(until: Date().addingTimeInterval(0.05))
        hosting.layoutSubtreeIfNeeded()

        let pixelWidth = Int((size.width * config.scale).rounded())
        let pixelHeight = Int((size.height * config.scale).rounded())
        guard let rep = NSBitmapImageRep(
            bitmapDataPlanes: nil, pixelsWide: pixelWidth, pixelsHigh: pixelHeight,
            bitsPerSample: 8, samplesPerPixel: 4, hasAlpha: true, isPlanar: false,
            colorSpaceName: .deviceRGB, bytesPerRow: 0, bitsPerPixel: 0
        ) else {
            result.error = "Could not allocate a \(pixelWidth)x\(pixelHeight) bitmap"
            return result
        }
        rep.size = size
        hosting.cacheDisplay(in: hosting.bounds, to: rep)
        window.contentView = nil
        window.close()

        result.pixelWidth = pixelWidth
        result.pixelHeight = pixelHeight
        result.pointWidth = Double(size.width)
        result.pointHeight = Double(size.height)
        result.error = __swiftLensWritePNG(rep, to: path)
        return result
    }

    @_cdecl("swiftlens_render_png")
    public func swiftlens_render_png(_ index: Int32, _ config: UnsafePointer<CChar>, _ path: UnsafePointer<CChar>) -> UnsafeMutablePointer<CChar>? {
        let decoded = __swiftLensDecodeConfig(config)
        let output = String(cString: path)
        let result = MainActor.assumeIsolated { __swiftLensRender(Int(index), decoded, output) }
        return __swiftLensEncode(result)
    }

    @_cdecl("swiftlens_make_nsview")
    public func swiftlens_make_nsview(_ index: Int32, _ config: UnsafePointer<CChar>) -> UnsafeMutableRawPointer? {
        let decoded = __swiftLensDecodeConfig(config)
        // Return the retained pointer as an Int bit pattern: `assumeIsolated` requires a Sendable result.
        let bits: Int = MainActor.assumeIsolated {
            let hosting = NSHostingView(rootView: __swiftLensConfigured(Int(index), decoded, forLiveView: true))
            hosting.appearance = NSAppearance(named: decoded.colorScheme == "dark" ? .darkAqua : .aqua)
            return Int(bitPattern: Unmanaged<NSView>.passRetained(hosting).toOpaque())
        }
        return UnsafeMutableRawPointer(bitPattern: bits)
    }
    #endif
    """#
}
